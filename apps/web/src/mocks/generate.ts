/**
 * Fixture generator.
 *
 * This file plays the part of the backend's database contents. It builds a
 * CONNECTED graph of documents rather than independent random rows:
 *
 *   PurchaseOrder -> GoodsReceipt -> StockMove(+) -> SupplierBill -> Payment
 *   SalesOrder    -> Delivery     -> StockMove(-) -> CustomerInvoice -> Payment
 *   every posted invoice / payment / delivery -> JournalEntry
 *   every state change -> AuditEvent
 *
 * Building it this way is the point. If the fixtures were random, the UI could
 * show a "related documents" panel that is decorative. Because they are
 * generated by walking the real business process, the traceability in the UI is
 * genuine, and any modelling mistake shows up immediately as data that will not
 * link.
 */

