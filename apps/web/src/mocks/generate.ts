/**
 * Create a balanced journal entry.
 * Throws if it does not balance — a guard that catches fixture bugs immediately,
 * and mirrors the constraint a real backend must enforce.
 */
function journal(
  entryDate: Date,
  memo: string,
  rawLines: { code: string; debit?: number; credit?: number; party?: { id: string; name: string }; description?: string }[],
  source: DocumentRef | undefined,
  by: UserRef,
  origin: 'system' | 'manual' = 'system',
): JournalEntry {
  const lines: JournalLine[] = rawLines.map((l, i) => {
    const acc = ACCOUNT_BY_CODE.get(l.code)!;
    return {
      id: `jl-${pad(jeCounter + 1, 5)}-${i}`,
      accountId: acc.id,
      accountCode: acc.code,
      accountName: acc.name,
      description: l.description,
      debit: money(l.debit ?? 0),
      credit: money(l.credit ?? 0),
      partyId: l.party?.id,
      partyName: l.party?.name,
    };
  });

  const totalDebit = sum(lines.map((l) => l.debit));
  const totalCredit = sum(lines.map((l) => l.credit));
  if (totalDebit.amount !== totalCredit.amount) {
    throw new Error(`Unbalanced journal entry "${memo}": ${totalDebit.amount} vs ${totalCredit.amount}`);
  }

  const entry: JournalEntry = {
    id: `je-${pad(++jeCounter, 5)}`,
    docNumber: `JE-2026-${pad(jeCounter)}`,
    docType: 'journal_entry',
    status: 'posted',
    entryDate: toISODate(entryDate),
    memo,
    lines,
    totalDebit,
    totalCredit,
    sourceDocument: source,
    origin,
    postedAt: toISODateTime(entryDate),
    postedBy: U['u-7']!,
    links: source ? [source] : [],
    ...stamps(entryDate, by),
  };
  JOURNAL_ENTRIES.push(entry);
  return entry;
}

