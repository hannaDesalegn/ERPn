let soCounter = 0;
let delCounter = 0;
let invCounter = 0;

const SO_PLAN: { daysBack: number; status: SalesOrderStatus }[] = [
  ...Array.from({ length: 34 }, (_, i) => ({ daysBack: 140 - i * 4, status: 'invoiced' as SalesOrderStatus })),
  ...Array.from({ length: 8 }, (_, i) => ({ daysBack: 26 - i * 3, status: 'delivered' as SalesOrderStatus })),
  ...Array.from({ length: 5 }, (_, i) => ({ daysBack: 12 - i * 2, status: 'partially_delivered' as SalesOrderStatus })),
  ...Array.from({ length: 7 }, (_, i) => ({ daysBack: 9 - i, status: 'confirmed' as SalesOrderStatus })),
  ...Array.from({ length: 4 }, (_, i) => ({ daysBack: 2 - i * 0.5, status: 'draft' as SalesOrderStatus })),
  { daysBack: 18, status: 'cancelled' },
  { daysBack: 45, status: 'cancelled' },
];

for (const plan of SO_PLAN) {
  const customer = rng.pick(CUSTOMERS.filter((c) => c.active));
  const orderedAt = daysAgo(Math.round(plan.daysBack));
  const rep = SALES_REPS.find((r) => r.id === customer.salesRepId) ?? SALES_REPS[0]!;
  const warehouse = rng.chance(0.8) ? WAREHOUSES[0]! : WAREHOUSES[1]!;

  const picks = rng.sample(PRODUCTS.filter((p) => p.active), rng.int(2, 6));

  const lines: SalesOrderLine[] = picks.map((p, i) => {
    // Trade customers buy in bulk, so order quantities scale with how fast the
    // product moves (its reorder point) rather than being a flat small number.
    const quantity = p.type === 'service' ? 1 : rng.int(6, Math.max(14, Math.round(p.reorderPoint * 0.45)));
    const discountPercent = rng.chance(0.3) ? rng.pick([2.5, 5, 7.5, 10]) : 0;
    const gross = multiply(p.salesPrice, quantity);
    const lineSubtotal = subtract(gross, percentOf(gross, discountPercent));
    const lineTax = percentOf(lineSubtotal, VAT_RATE);
    return {
      id: `sol-${pad(soCounter + 1)}-${i}`,
      productId: p.id,
      productSku: p.sku,
      productName: p.name,
      quantity,
      unitPrice: p.salesPrice,
      discountPercent,
      taxRatePercent: VAT_RATE,
      lineSubtotal,
      lineTax,
      lineTotal: add(lineSubtotal, lineTax),
      deliveredQuantity: 0,
      invoicedQuantity: 0,
    };
  });

  const subtotal = sum(lines.map((l) => l.lineSubtotal));
  const taxTotal = sum(lines.map((l) => l.lineTax));
  const total = add(subtotal, taxTotal);

  const so: SalesOrder = {
    id: `so-${pad(++soCounter, 3)}`,
    docNumber: `SO-2026-${pad(soCounter)}`,
    docType: 'sales_order',
    status: plan.status,
    customer: { id: customer.id, name: customer.name, type: 'customer' },
    orderDate: toISODate(orderedAt),
    expectedDeliveryDate: addDays(toISODate(orderedAt), rng.int(3, 12)),
    warehouseId: warehouse.id,
    warehouseName: warehouse.name,
    salesRep: ref(rep),
    lines,
    subtotal,
    taxTotal,
    total,
    currency: 'USD',
    invoicedTotal: zero(),
    links: [],
    ...stamps(orderedAt, ref(rep)),
  };

  audit(orderedAt, ref(rep), 'created', docRef(so, 'sales_order'), `Created sales order ${so.docNumber} for ${customer.name}`);

  if (plan.status === 'cancelled') {
    audit(daysAgo(Math.round(plan.daysBack) - 1), ref(rep), 'cancelled', docRef(so, 'sales_order'), `Cancelled sales order ${so.docNumber}`);
    SALES_ORDERS.push(so);
    continue;
  }

  if (plan.status !== 'draft') {
    audit(orderedAt, ref(rep), 'confirmed', docRef(so, 'sales_order'), `Confirmed sales order ${so.docNumber} for ${customer.name}`);
  }

  // ---- Delivery ---------------------------------------------------------
  const ships = ['partially_delivered', 'delivered', 'invoiced'].includes(plan.status);
  if (ships) {
    const partial = plan.status === 'partially_delivered';
    const shippedAt = daysAgo(Math.max(0, Math.round(plan.daysBack) - rng.int(2, 6)));
    const stockLines = lines.filter((l) => PRODUCTS.find((p) => p.id === l.productId)!.type === 'stockable');

    const delLines: DeliveryLine[] = stockLines.map((l, i) => ({
      id: `dl-${pad(delCounter + 1)}-${i}`,
      productId: l.productId,
      productSku: l.productSku,
      productName: l.productName,
      orderedQuantity: l.quantity,
      shippedQuantity: partial && i === 0 ? Math.floor(l.quantity * 0.5) : l.quantity,
    }));

    if (delLines.length) {
      const delivery: Delivery = {
        id: `del-${pad(++delCounter, 3)}`,
        docNumber: `DEL-2026-${pad(delCounter)}`,
        docType: 'delivery',
        status: 'delivered',
        customer: so.customer,
        salesOrderId: so.id,
        salesOrderNumber: so.docNumber,
        warehouseId: so.warehouseId,
        warehouseName: so.warehouseName,
        scheduledDate: so.expectedDeliveryDate!,
        shippedDate: toISODate(shippedAt),
        carrier: rng.pick(['DHL Freight', 'DB Schenker', 'Own Fleet', 'GLS']),
        trackingNumber: `TRK${rng.int(10000000, 99999999)}`,
        lines: delLines,
        links: [docRef(so, 'sales_order')],
        ...stamps(shippedAt, U['u-6']!),
      };
      DELIVERIES.push(delivery);
      so.links.push(docRef(delivery, 'delivery'));

      let cogs = zero();
      for (const dl of delLines) {
        const product = PRODUCTS.find((p) => p.id === dl.productId)!;
        const line = lines.find((l) => l.productId === dl.productId)!;
        line.deliveredQuantity = dl.shippedQuantity;
        stockMove(product, so.warehouseId, -dl.shippedQuantity, 'sales_delivery', product.costPrice, shippedAt, docRef(delivery, 'delivery'), U['u-6']!);
        cogs = add(cogs, multiply(product.costPrice, dl.shippedQuantity));
      }

      // Shipping goods is an ACCOUNTING event too: value leaves inventory and
      // becomes cost of goods sold. Revenue is recognised separately, at invoice.
      if (cogs.amount > 0) {
        journal(
          shippedAt,
          `Cost of goods sold for ${delivery.docNumber}`,
          [
            { code: '5010', debit: cogs.amount / 100, description: 'Goods shipped to customer' },
            { code: '1300', credit: cogs.amount / 100 },
          ],
          docRef(delivery, 'delivery'),
          U['u-7']!,
        );
      }

      audit(shippedAt, U['u-6']!, 'shipped', docRef(delivery, 'delivery'), `Shipped ${delivery.docNumber} for ${so.docNumber}`);
    }
  }

  // ---- Invoice ----------------------------------------------------------
  if (plan.status === 'invoiced') {
    const invoicedAt = daysAgo(Math.max(0, Math.round(plan.daysBack) - rng.int(6, 10)));
    const invoiceDate = toISODate(invoicedAt);
    const dueDate = addDays(invoiceDate, customer.paymentTerms.daysUntilDue);

    const invLines: InvoiceLine[] = lines.map((l, i) => ({
      id: `il-${pad(invCounter + 1)}-${i}`,
      productId: l.productId,
      productSku: l.productSku,
      description: l.productName,
      quantity: l.quantity,
      unitPrice: l.unitPrice,
      discountPercent: l.discountPercent,
      taxRatePercent: VAT_RATE,
      lineSubtotal: l.lineSubtotal,
      lineTax: l.lineTax,
      lineTotal: l.lineTotal,
      accountCode: '4010',
    }));

    // Collection profile. Tuned so the receivables ledger carries a realistic
    // amount of unpaid balance: a distributor selling on Net 30–60 terms always
    // has a substantial book of money owed. If almost everything were marked
    // paid, the aging chart and the overdue alerts would have nothing to show
    // and the dashboard would misrepresent how this kind of business runs.
    const roll = rng.next();
    const paidFully = roll < 0.34;
    const paidPartly = !paidFully && roll < 0.6;
    const paidAmount = paidFully ? total : paidPartly ? multiply(total, rng.float(0.3, 0.7)) : zero();
    const balanceDue = subtract(total, paidAmount);
    const overdue = balanceDue.amount > 0 && new Date(`${dueDate}T00:00:00Z`) < REFERENCE_TODAY;
    const status: InvoiceStatus = paidFully ? 'paid' : overdue ? 'overdue' : paidPartly ? 'partially_paid' : 'posted';

    const invoice: CustomerInvoice = {
      id: `ci-${pad(++invCounter, 3)}`,
      docNumber: `INV-2026-${pad(invCounter)}`,
      docType: 'customer_invoice',
      status,
      party: so.customer,
      invoiceDate,
      dueDate,
      lines: invLines,
      subtotal,
      taxTotal,
      total,
      paidAmount,
      balanceDue,
      currency: 'USD',
      postedAt: toISODateTime(invoicedAt),
      postedBy: U['u-7']!,
      salesOrderIds: [so.id],
      salesOrderNumbers: [so.docNumber],
      links: [docRef(so, 'sales_order')],
      ...stamps(invoicedAt, U['u-7']!),
    };

    const je = journal(
      invoicedAt,
      `Customer invoice ${invoice.docNumber} for ${customer.name}`,
      [
        { code: '1200', debit: total.amount / 100, party: { id: customer.id, name: customer.name } },
        { code: '4010', credit: subtotal.amount / 100, description: 'Product sales' },
        { code: '2100', credit: taxTotal.amount / 100, description: 'Output VAT' },
      ],
      docRef(invoice, 'customer_invoice'),
      U['u-7']!,
    );
    invoice.journalEntryId = je.id;
    invoice.journalEntryNumber = je.docNumber;
    invoice.links.push(docRef(je, 'journal_entry'));

    /**
     * The order carries the WHOLE downstream trail, not just its direct
     * children. Strictly, the journal entry belongs to the invoice and the
     * invoice belongs to the order. But the question a user asks standing on an
     * order is "what happened to this in the end", and making them hop through
     * three screens to answer it is exactly the friction an ERP should remove.
     * Real systems denormalise the trail for the same reason.
     */
    so.links.push(docRef(je, 'journal_entry'));

    CUSTOMER_INVOICES.push(invoice);
    so.invoicedTotal = total;
    so.links.push(docRef(invoice, 'customer_invoice'));
    for (const l of lines) l.invoicedQuantity = l.quantity;

    audit(invoicedAt, U['u-7']!, 'posted', docRef(invoice, 'customer_invoice'), `Posted invoice ${invoice.docNumber} for ${customer.name}`);

    if (paidAmount.amount > 0) {
      const paidAt = daysAgo(Math.max(0, Math.round(plan.daysBack) - rng.int(11, 40)));
      const cashAccount = rng.pick(CASH_ACCOUNTS.filter((a) => a.code !== '1030'));
      const payment: Payment = {
        id: `pay-${pad(++payCounter, 3)}`,
        docNumber: `PAY-IN-${pad(payCounter)}`,
        docType: 'customer_payment',
        status: 'posted',
        direction: 'inbound',
        party: so.customer,
        paymentDate: toISODate(paidAt),
        method: rng.pick(['bank_transfer', 'bank_transfer', 'bank_transfer', 'card', 'cheque'] as const),
        amount: paidAmount,
        currency: 'USD',
        cashAccountId: cashAccount.id,
        cashAccountName: cashAccount.name,
        reference: `RCPT-${rng.int(1000000, 9999999)}`,
        allocations: [{ invoiceId: invoice.id, invoiceNumber: invoice.docNumber, amountApplied: paidAmount }],
        unallocatedAmount: zero(),
        links: [docRef(invoice, 'customer_invoice')],
        ...stamps(paidAt, U['u-7']!),
      };

      const payJe = journal(
        paidAt,
        `Receipt from ${customer.name} for ${invoice.docNumber}`,
        [
          { code: cashAccount.code, debit: paidAmount.amount / 100 },
          { code: '1200', credit: paidAmount.amount / 100, party: { id: customer.id, name: customer.name } },
        ],
        docRef(payment, 'customer_payment'),
        U['u-7']!,
      );
      payment.journalEntryId = payJe.id;
      payment.journalEntryNumber = payJe.docNumber;
      payment.links.push(docRef(payJe, 'journal_entry'));
      invoice.links.push(docRef(payment, 'customer_payment'));
      so.links.push(docRef(payment, 'customer_payment'));

      PAYMENTS.push(payment);
      audit(paidAt, U['u-7']!, 'paid', docRef(payment, 'customer_payment'), `Received ${customer.name} payment against ${invoice.docNumber}`);
    }
  }

  SALES_ORDERS.push(so);
}

