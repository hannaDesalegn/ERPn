// A stock adjustment after a cycle count, with the shrinkage posted to expense.
{
  const countedAt = daysAgo(9);
  const picks = rng.sample(STOCKABLE, 4);
  const adj: InventoryAdjustment = {
    id: 'adj-002',
    docNumber: 'ADJ-2026-0002',
    docType: 'inventory_adjustment',
    status: 'posted',
    warehouseId: 'wh-1',
    warehouseName: WAREHOUSES[0]!.name,
    countDate: toISODate(countedAt),
    reason: 'cycle_count',
    lines: [],
    links: [],
    notes: 'Quarterly cycle count, aisle C.',
    ...stamps(countedAt, U['u-6']!),
  };

  let shrinkage = zero();
  picks.forEach((p, i) => {
    const difference = rng.pick([-3, -2, -1, 1, -5]);

    // What the system believed was on the shelf at the moment of the count:
    // the sum of every movement for this product and warehouse recorded before
    // then. Derived from the ledger rather than stored, exactly like the stock
    // projection, so the variance the adjustment reports is a real subtraction.
    const countedAtISO = toISODateTime(countedAt);
    const systemQuantity = STOCK_MOVES.filter(
      (m) => m.productId === p.id && m.warehouseId === 'wh-1' && m.occurredAt <= countedAtISO,
    ).reduce((total, m) => total + m.quantity, 0);

    adj.lines.push({
      id: `adjl-2-${i}`,
      productId: p.id,
      productSku: p.sku,
      productName: p.name,
      systemQuantity,
      countedQuantity: systemQuantity + difference,
      difference,
    });
    stockMove(p, 'wh-1', difference, 'adjustment', p.costPrice, countedAt, docRef(adj, 'inventory_adjustment'), U['u-6']!);
    if (difference < 0) shrinkage = add(shrinkage, multiply(p.costPrice, -difference));
  });

  if (shrinkage.amount > 0) {
    journal(
      countedAt,
      `Inventory shrinkage for ${adj.docNumber}`,
      [
        { code: '5030', debit: shrinkage.amount / 100, description: 'Cycle count variance' },
        { code: '1300', credit: shrinkage.amount / 100 },
      ],
      docRef(adj, 'inventory_adjustment'),
      U['u-7']!,
    );
  }

  ADJUSTMENTS.push(adj);
  audit(countedAt, U['u-6']!, 'posted', docRef(adj, 'inventory_adjustment'), `Posted cycle count adjustment ${adj.docNumber}`);
}

