let poCounter = 0;
let grCounter = 0;
let billCounter = 0;
let payCounter = 0;

const PO_PLAN: { daysBack: number; status: PurchaseOrderStatus }[] = [
  ...Array.from({ length: 14 }, (_, i) => ({ daysBack: 150 - i * 9, status: 'billed' as PurchaseOrderStatus })),
  ...Array.from({ length: 6 }, (_, i) => ({ daysBack: 40 - i * 5, status: 'received' as PurchaseOrderStatus })),
  ...Array.from({ length: 4 }, (_, i) => ({ daysBack: 22 - i * 4, status: 'partially_received' as PurchaseOrderStatus })),
  ...Array.from({ length: 5 }, (_, i) => ({ daysBack: 14 - i * 2, status: 'approved' as PurchaseOrderStatus })),
  ...Array.from({ length: 4 }, (_, i) => ({ daysBack: 6 - i, status: 'pending_approval' as PurchaseOrderStatus })),
  ...Array.from({ length: 3 }, (_, i) => ({ daysBack: 3 - i, status: 'draft' as PurchaseOrderStatus })),
  { daysBack: 30, status: 'cancelled' },
];

for (const plan of PO_PLAN) {
  const supplier = rng.pick(SUPPLIERS);
  const orderedAt = daysAgo(plan.daysBack);
  const warehouse = rng.chance(0.75) ? WAREHOUSES[0]! : WAREHOUSES[1]!;

  // Buy products this supplier plausibly sells.
  const supplierCategories = Object.entries(CATEGORY_SUPPLIER)
    .filter(([, sid]) => sid === supplier.id)
    .map(([cid]) => cid);
  const pool = supplierCategories.length
    ? STOCKABLE.filter((p) => supplierCategories.includes(p.categoryId))
    : STOCKABLE;
  const picks = rng.sample(pool.length >= 3 ? pool : STOCKABLE, rng.int(2, 5));

  const lines: PurchaseOrderLine[] = picks.map((p, i) => {
    const quantity = Math.max(10, Math.round(p.reorderQuantity * rng.float(0.4, 1.1)));
    const unitCost = multiply(p.costPrice, rng.float(0.96, 1.05));
    const lineSubtotal = multiply(unitCost, quantity);
    const lineTax = percentOf(lineSubtotal, VAT_RATE);
    return {
      id: `pol-${pad(poCounter + 1)}-${i}`,
      productId: p.id,
      productSku: p.sku,
      productName: p.name,
      quantity,
      unitCost,
      taxRatePercent: VAT_RATE,
      lineSubtotal,
      lineTax,
      lineTotal: add(lineSubtotal, lineTax),
      receivedQuantity: 0,
      billedQuantity: 0,
    };
  });

  const subtotal = sum(lines.map((l) => l.lineSubtotal));
  const taxTotal = sum(lines.map((l) => l.lineTax));
  const total = add(subtotal, taxTotal);

  const po: PurchaseOrder = {
    id: `po-${pad(++poCounter, 3)}`,
    docNumber: `PO-2026-${pad(poCounter)}`,
    docType: 'purchase_order',
    status: plan.status,
    supplier: { id: supplier.id, name: supplier.name, type: 'supplier' },
    orderDate: toISODate(orderedAt),
    expectedDate: addDays(toISODate(orderedAt), supplier.leadTimeDays),
    warehouseId: warehouse.id,
    warehouseName: warehouse.name,
    requestedBy: U['u-5']!,
    lines,
    subtotal,
    taxTotal,
    total,
    currency: 'USD',
    billedTotal: zero(),
    links: [],
    ...stamps(orderedAt, U['u-5']!),
  };

  audit(orderedAt, U['u-5']!, 'created', docRef(po, 'purchase_order'), `Created purchase order ${po.docNumber} for ${supplier.name}`);

  const isApproved = !['draft', 'pending_approval', 'cancelled'].includes(plan.status);
  if (isApproved) {
    const approvedAt = daysAgo(plan.daysBack - 1);
    po.approvedBy = U['u-2']!;
    po.approvedAt = toISODateTime(approvedAt);
    audit(approvedAt, U['u-2']!, 'approved', docRef(po, 'purchase_order'), `Approved purchase order ${po.docNumber}`);
  }

  if (plan.status === 'cancelled') {
    audit(daysAgo(plan.daysBack - 2), U['u-2']!, 'cancelled', docRef(po, 'purchase_order'), `Cancelled purchase order ${po.docNumber}`);
  }

  // ---- Goods receipt --------------------------------------------------
  const receives = ['partially_received', 'received', 'billed'].includes(plan.status);
  if (receives) {
    const partial = plan.status === 'partially_received';
    const receivedAt = daysAgo(Math.max(0, plan.daysBack - supplier.leadTimeDays));

    const gr: GoodsReceipt = {
      id: `gr-${pad(++grCounter, 3)}`,
      docNumber: `GR-2026-${pad(grCounter)}`,
      docType: 'goods_receipt',
      status: 'received',
      supplier: po.supplier,
      purchaseOrderId: po.id,
      purchaseOrderNumber: po.docNumber,
      warehouseId: po.warehouseId,
      warehouseName: po.warehouseName,
      receivedDate: toISODate(receivedAt),
      receivedBy: U['u-6']!,
      supplierDeliveryNote: `DN-${rng.int(100000, 999999)}`,
      lines: lines.map((l, i) => {
        const receivedQuantity = partial && i === 0 ? Math.floor(l.quantity * 0.6) : l.quantity;
        const rejected = rng.chance(0.06) ? Math.min(2, Math.floor(receivedQuantity * 0.02)) : 0;
        return {
          id: `grl-${pad(grCounter)}-${i}`,
          productId: l.productId,
          productSku: l.productSku,
          productName: l.productName,
          orderedQuantity: l.quantity,
          receivedQuantity,
          rejectedQuantity: rejected,
        };
      }),
      links: [docRef(po, 'purchase_order')],
      ...stamps(receivedAt, U['u-6']!),
    };
    GOODS_RECEIPTS.push(gr);
    po.links.push(docRef(gr, 'goods_receipt'));

    // Goods physically arrived -> stock moves. THIS is what changes inventory.
    for (const grl of gr.lines) {
      const product = PRODUCTS.find((p) => p.id === grl.productId)!;
      const poLine = lines.find((l) => l.productId === grl.productId)!;
      const good = grl.receivedQuantity - grl.rejectedQuantity;
      poLine.receivedQuantity = grl.receivedQuantity;
      if (good > 0) {
        stockMove(product, po.warehouseId, good, 'purchase_receipt', poLine.unitCost, receivedAt, docRef(gr, 'goods_receipt'), U['u-6']!);
      }
    }

    audit(receivedAt, U['u-6']!, 'received', docRef(gr, 'goods_receipt'), `Received goods ${gr.docNumber} against ${po.docNumber}`);

    // ---- Supplier bill ------------------------------------------------
    if (plan.status === 'billed') {
      const billedAt = daysAgo(Math.max(0, plan.daysBack - supplier.leadTimeDays - 2));
      const billDate = toISODate(billedAt);
      const dueDate = addDays(billDate, supplier.paymentTerms.daysUntilDue);
      const hasVariance = rng.chance(0.12);

      const billLines: InvoiceLine[] = lines.map((l, i) => ({
        id: `bl-${pad(billCounter + 1)}-${i}`,
        productId: l.productId,
        productSku: l.productSku,
        description: l.productName,
        quantity: l.quantity,
        unitPrice: l.unitCost,
        discountPercent: 0,
        taxRatePercent: VAT_RATE,
        lineSubtotal: l.lineSubtotal,
        lineTax: l.lineTax,
        lineTotal: l.lineTotal,
        accountCode: '1300',
      }));

      const paidFully = rng.chance(0.45);
      const paidPartly = !paidFully && rng.chance(0.35);
      const paidAmount = paidFully ? total : paidPartly ? multiply(total, 0.5) : zero();
      const balanceDue = subtract(total, paidAmount);
      const overdue = balanceDue.amount > 0 && new Date(`${dueDate}T00:00:00Z`) < REFERENCE_TODAY;

      const status: InvoiceStatus = paidFully ? 'paid' : overdue ? 'overdue' : paidPartly ? 'partially_paid' : 'posted';

      const bill: import('@/domain').SupplierBill = {
        id: `sb-${pad(++billCounter, 3)}`,
        docNumber: `BILL-2026-${pad(billCounter)}`,
        docType: 'supplier_bill',
        status,
        party: po.supplier,
        invoiceDate: billDate,
        dueDate,
        lines: billLines,
        subtotal,
        taxTotal,
        total,
        paidAmount,
        balanceDue,
        currency: 'USD',
        postedAt: toISODateTime(billedAt),
        postedBy: U['u-7']!,
        purchaseOrderIds: [po.id],
        purchaseOrderNumbers: [po.docNumber],
        supplierReference: `${supplier.code}-${rng.int(10000, 99999)}`,
        matchStatus: hasVariance ? rng.pick(['quantity_variance', 'price_variance'] as const) : 'matched',
        links: [docRef(po, 'purchase_order'), docRef(gr, 'goods_receipt')],
        ...stamps(billedAt, U['u-7']!),
      };

      // Posting the bill produces the accounting consequence.
      const je = journal(
        billedAt,
        `Supplier bill ${bill.docNumber} from ${supplier.name}`,
        [
          { code: '1300', debit: subtotal.amount / 100, description: 'Goods received into stock' },
          { code: '2100', debit: taxTotal.amount / 100, description: 'Input VAT' },
          { code: '2010', credit: total.amount / 100, party: { id: supplier.id, name: supplier.name } },
        ],
        docRef(bill, 'supplier_bill'),
        U['u-7']!,
      );
      bill.journalEntryId = je.id;
      bill.journalEntryNumber = je.docNumber;
      bill.links.push(docRef(je, 'journal_entry'));

      SUPPLIER_BILLS.push(bill);
      po.status = 'billed';
      po.billedTotal = total;
      po.links.push(docRef(bill, 'supplier_bill'));
      for (const l of lines) l.billedQuantity = l.quantity;

      audit(billedAt, U['u-7']!, 'posted', docRef(bill, 'supplier_bill'), `Posted supplier bill ${bill.docNumber} for ${supplier.name}`);

      // ---- Supplier payment -------------------------------------------
      if (paidAmount.amount > 0) {
        const paidAt = daysAgo(Math.max(0, plan.daysBack - supplier.leadTimeDays - 2 - rng.int(5, 25)));
        const cashAccount = rng.pick(CASH_ACCOUNTS.filter((a) => a.code !== '1030'));
        const allocation: PaymentAllocation = {
          invoiceId: bill.id,
          invoiceNumber: bill.docNumber,
          amountApplied: paidAmount,
        };

        const payment: Payment = {
          id: `pay-${pad(++payCounter, 3)}`,
          docNumber: `PAY-OUT-${pad(payCounter)}`,
          docType: 'supplier_payment',
          status: 'posted',
          direction: 'outbound',
          party: po.supplier,
          paymentDate: toISODate(paidAt),
          method: rng.pick(['bank_transfer', 'bank_transfer', 'cheque'] as const),
          amount: paidAmount,
          currency: 'USD',
          cashAccountId: cashAccount.id,
          cashAccountName: cashAccount.name,
          reference: `SEPA-${rng.int(1000000, 9999999)}`,
          allocations: [allocation],
          unallocatedAmount: zero(),
          links: [docRef(bill, 'supplier_bill')],
          ...stamps(paidAt, U['u-7']!),
        };

        const payJe = journal(
          paidAt,
          `Payment to ${supplier.name} for ${bill.docNumber}`,
          [
            { code: '2010', debit: paidAmount.amount / 100, party: { id: supplier.id, name: supplier.name } },
            { code: cashAccount.code, credit: paidAmount.amount / 100 },
          ],
          docRef(payment, 'supplier_payment'),
          U['u-7']!,
        );
        payment.journalEntryId = payJe.id;
        payment.journalEntryNumber = payJe.docNumber;
        payment.links.push(docRef(payJe, 'journal_entry'));
        bill.links.push(docRef(payment, 'supplier_payment'));

        PAYMENTS.push(payment);
        audit(paidAt, U['u-7']!, 'paid', docRef(payment, 'supplier_payment'), `Paid ${supplier.name} against ${bill.docNumber}`);
      }
    }
  }

  PURCHASE_ORDERS.push(po);
}

